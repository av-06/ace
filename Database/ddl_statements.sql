CREATE TABLE Account(
	Account_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Account_Name NVARCHAR(30) NOT NULL,
	Account_Password CHAR(31) NOT NULL);

CREATE TABLE Teacher(
	Teacher_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Account_Id INT FOREIGN KEY REFERENCES Account(Account_Id) ON DELETE CASCADE);
	
CREATE TABLE Student(
	Student_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Account_Id INT FOREIGN KEY REFERENCES Account(Account_Id) ON DELETE CASCADE);

CREATE TABLE Teacher_Has_Student(
	Teacher_Id INT FOREIGN KEY REFERENCES Teacher(Teacher_Id) ON DELETE NO ACTION,
	Student_Id INT FOREIGN KEY REFERENCES Student(Student_Id) ON DELETE NO ACTION,
	CONSTRAINT PK_Teacher_Has_Student PRIMARY KEY (Teacher_Id, Student_Id));

CREATE TABLE Deck(
	Deck_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Deck_Name NVARCHAR(50) NOT NULL,
	Deck_Description NVARCHAR(100),
	Deck_Owner INT FOREIGN KEY REFERENCES Account(Account_Id) ON DELETE CASCADE);
	
CREATE TABLE Card(
	Card_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Card_Front NVARCHAR(max) NOT NULL,
	Card_Back NVARCHAR(max) NOT NULL,
	Card_DueDate DATE DEFAULT NULL,
	Card_ReviewInterval INT DEFAULT 1,
	Card_State CHAR(8),
	Card_Type CHAR(14),
	Card_Owner INT FOREIGN KEY REFERENCES Account(Account_Id) ON DELETE NO ACTION,
	Card_Deck INT FOREIGN KEY REFERENCES Deck(Deck_Id) ON DELETE CASCADE);

CREATE TABLE Tag(
	Tag_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Tag_Name NVARCHAR(50) NOT NULL);

CREATE TABLE Card_Has_Tag(
	Card_Id INT FOREIGN KEY REFERENCES Card(Card_Id) ON DELETE CASCADE,
	Tag_Id INT FOREIGN KEY REFERENCES Tag(Tag_Id) ON DELETE CASCADE,
	CONSTRAINT PK_Card_Has_Tag PRIMARY KEY (Card_id, Tag_id));

CREATE TABLE StudySession(
	Sesh_Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
	Sesh_Date DATE NOT NULL,
	Sesh_SuccessCount INT NOT NULL,
	Sesh_FailCount INT NOT NULL,
	Sesh_CardsDoneCount INT NOT NULL,
	Sesh_User INT FOREIGN KEY REFERENCES Account(Account_Id) ON DELETE CASCADE,
	Sesh_Deck INT FOREIGN KEY REFERENCES Deck(Deck_Id) ON DELETE NO ACTION);
